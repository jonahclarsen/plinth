import { test, expect } from '@playwright/test'
test('music access lists only the permissions a link uses, with a live action for each',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.setViewportSize({width:460,height:248})
 await page.goto('/?access=1')
 await expect(page.getByRole('heading')).toHaveText('Plinth needs access to Music')
 await expect(page.getByText('To open the playlist “Evening records”.')).toBeVisible()
 await expect(page.locator('li')).toHaveCount(1)
 await expect(page.locator('li.denied')).toContainText('Control Music')
 await expect(page.getByRole('button',{name:'Open System Settings for Control Music'})).toBeVisible()
 await expect(page.getByRole('button',{name:'Try again'})).toBeDisabled()
 const footer=await page.locator('.access-foot').boundingBox()
 expect(footer!.y+footer!.height).toBeLessThanOrEqual(248)
 await page.goto('/?access=artist')
 await expect(page.locator('li')).toHaveCount(3)
 await expect(page.locator('li.allowed .state-label')).toHaveText('Allowed')
 await expect(page.locator('li.not-requested').getByRole('button',{name:'Allow…'})).toBeVisible()
 await expect(page.locator('li.denied')).toContainText('Accessibility')
 expect(errors).toEqual([])
})
