test('all history entries remain reachable in a narrow window',async({page})=>{
 await page.setViewportSize({width:640,height:500})
 await page.goto('/?demo=1')
 for(let index=0;index<8;index++){
  if(await page.locator('.settings-dialog').isVisible())await page.getByRole('button',{name:'Back to Settings',exact:true}).click();else await page.getByRole('button',{name:'Settings',exact:true}).click()
  await page.getByRole('button',{name:index%2===0?'Light':'Dark',exact:true}).click()
  await historyPage(page)
 }
 await expect(page.locator('.history-list>li')).toHaveCount(9)
 const baseline=page.getByRole('button',{name:'Restore state 1',exact:true})
 await baseline.scrollIntoViewIfNeeded();await expect(baseline).toBeInViewport()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await baseline.click();await expect(page.locator('.history-list>li.current')).toContainText('Starting state')
 await expect(page.locator('.history-list>li')).toHaveCount(9)
})
